#!/bin/bash

# This file is intended to be sourced by other CommonsenseQA launcher scripts.

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CODI_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
BASELINE_ROOT="$(cd "${CODI_DIR}/.." && pwd)"

if [[ -f "${CODI_DIR}/config.env" ]]; then
  # shellcheck disable=SC1091
  source "${CODI_DIR}/config.env"
fi

export CODI_VENV_PATH="${CODI_VENV_PATH:-${BASELINE_ROOT}/.venv/bin/activate}"
export CODI_RUN_ROOT="${CODI_RUN_ROOT:-${BASELINE_ROOT}/CODI_rebuttal_runs/rebuttal_20260325}"

# Reuse shared staged Qwen assets from the existing multi-backbone rebuttal root.
export CODI_SHARED_MULTIMODEL_TAG="${CODI_SHARED_MULTIMODEL_TAG:-multimodel_gsm8k_math500_aime_v1}"
export CODI_SHARED_MULTIMODEL_ROOT="${CODI_SHARED_MULTIMODEL_ROOT:-${CODI_RUN_ROOT}/${CODI_SHARED_MULTIMODEL_TAG}}"
export CODI_COMMONSENSE_STAGE_TAG="${CODI_COMMONSENSE_STAGE_TAG:-qwen_commonsense_fast_iteration_v1}"
export CODI_COMMONSENSE_ROOT="${CODI_COMMONSENSE_ROOT:-${CODI_RUN_ROOT}/${CODI_COMMONSENSE_STAGE_TAG}}"

export CODI_COMMONSENSE_MODEL_ROOT="${CODI_COMMONSENSE_MODEL_ROOT:-${CODI_SHARED_MULTIMODEL_ROOT}/models}"
export CODI_COMMONSENSE_MANIFEST_DIR="${CODI_COMMONSENSE_MANIFEST_DIR:-${CODI_SHARED_MULTIMODEL_ROOT}/manifests}"
export CODI_COMMONSENSE_SAVE_DIR="${CODI_COMMONSENSE_ROOT}/outputs"
export CODI_COMMONSENSE_RESULT_DIR="${CODI_COMMONSENSE_ROOT}/results"
export CODI_COMMONSENSE_LOG_DIR="${CODI_COMMONSENSE_ROOT}/logs"
export CODI_COMMONSENSE_CACHE_DIR="${CODI_COMMONSENSE_ROOT}/cache"

export CODI_COMMONSENSE_HF_HOME="${CODI_COMMONSENSE_HF_HOME:-${CODI_COMMONSENSE_ROOT}/hf_home}"
export CODI_COMMONSENSE_HF_DATASETS_CACHE="${CODI_COMMONSENSE_HF_DATASETS_CACHE:-${CODI_COMMONSENSE_ROOT}/hf_datasets_cache}"
export CODI_COMMONSENSE_MODELSCOPE_CACHE="${CODI_COMMONSENSE_MODELSCOPE_CACHE:-${CODI_COMMONSENSE_ROOT}/modelscope_cache}"
export HF_HOME="${HF_HOME:-${CODI_COMMONSENSE_HF_HOME}}"
export HF_DATASETS_CACHE="${HF_DATASETS_CACHE:-${CODI_COMMONSENSE_HF_DATASETS_CACHE}}"
export TRANSFORMERS_CACHE="${TRANSFORMERS_CACHE:-${CODI_COMMONSENSE_HF_HOME}/transformers}"
export MODELSCOPE_CACHE="${MODELSCOPE_CACHE:-${CODI_COMMONSENSE_MODELSCOPE_CACHE}}"
export HF_HUB_DISABLE_XET="${HF_HUB_DISABLE_XET:-1}"

export CODI_MM_QWEN3_PATH="${CODI_MM_QWEN3_PATH:-${CODI_COMMONSENSE_MODEL_ROOT}/Qwen3-4B}"
export CODI_MM_QWEN3_1P7B_PATH="${CODI_MM_QWEN3_1P7B_PATH:-${CODI_COMMONSENSE_MODEL_ROOT}/Qwen3-1.7B}"

mkdir -p \
  "${CODI_COMMONSENSE_ROOT}" \
  "${CODI_COMMONSENSE_SAVE_DIR}" \
  "${CODI_COMMONSENSE_RESULT_DIR}" \
  "${CODI_COMMONSENSE_LOG_DIR}" \
  "${CODI_COMMONSENSE_CACHE_DIR}" \
  "${CODI_COMMONSENSE_HF_HOME}" \
  "${HF_DATASETS_CACHE}" \
  "${TRANSFORMERS_CACHE}" \
  "${MODELSCOPE_CACHE}"
