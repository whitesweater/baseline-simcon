#!/bin/bash
# =============================================================================
# Latent Sweep 并发测试脚本 - 同时运行两组模型
# =============================================================================
# 在一个终端中并发执行两组测试，等待全部完成
#
# 用法:
#   ./test_latent_sweep_all.sh                 # 并发测试所有模型
#   ./test_latent_sweep_all.sh --start 1 --end 6
#   ./test_latent_sweep_all.sh --dry-run
# =============================================================================

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

echo "============================================================================"
echo "Latent Sweep 并发测试 - 同时运行两组模型"
echo "============================================================================"
echo "  第1组: codi, codi_sircl"
echo "  第2组: simcon, sircl"
echo "============================================================================"
echo ""

# 启动第1组（后台运行）
echo "[$(date '+%H:%M:%S')] 🚀 启动第1组测试 (codi, codi_sircl)..."
"${SCRIPT_DIR}/test_latent_sweep_group1.sh" "$@" &
PID1=$!

# 启动第2组（后台运行）
echo "[$(date '+%H:%M:%S')] 🚀 启动第2组测试 (simcon, sircl)..."
"${SCRIPT_DIR}/test_latent_sweep_group2.sh" "$@" &
PID2=$!

echo ""
echo "[$(date '+%H:%M:%S')] ⏳ 等待两组测试完成..."
echo "  第1组 PID: ${PID1}"
echo "  第2组 PID: ${PID2}"
echo ""

# 等待两个进程都完成
wait $PID1
STATUS1=$?

wait $PID2
STATUS2=$?

echo ""
echo "============================================================================"
echo "[$(date '+%H:%M:%S')] 并发测试完成"
echo "============================================================================"
echo "  第1组 (codi, codi_sircl): $([ $STATUS1 -eq 0 ] && echo '✅ 成功' || echo '❌ 失败')"
echo "  第2组 (simcon, sircl):    $([ $STATUS2 -eq 0 ] && echo '✅ 成功' || echo '❌ 失败')"
echo "============================================================================"

# 如果任一组失败，返回非零退出码
[[ $STATUS1 -ne 0 || $STATUS2 -ne 0 ]] && exit 1 || exit 0
