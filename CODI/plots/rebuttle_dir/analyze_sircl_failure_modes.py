#!/usr/bin/env python3
"""
Pairwise latent-trajectory analysis for rebuttal questions about SIRCL.

This script compares two evaluated `run_*` directories at the sample level:
one baseline run and one `+SIRCL` run. It is designed to answer questions like:

1. Does SIRCL help more when the baseline is already correct?
2. When baseline trajectories are wrong, do their geometry statistics look
   different from correct ones?
3. Among baseline-wrong samples, what separates recovered cases from
   still-wrong cases?

Expected input directory structure (generated by `test_multi_dataset.py`):
  run_0/
    predictions.json
    latents.json
    metrics.json
    raw_outputs.json          # optional
    trajectory_stats.json     # optional

Main outputs:
  - sample_level.csv
  - gain_by_baseline_bucket.csv
  - transition_summary.csv
  - geometry_group_summary.csv
  - radius_profiles.csv
  - failure_examples.csv
  - summary.json
  - summary.md
  - several PNG figures under the output directory

Example:
python3 CODI/plots/analyze_sircl_failure_modes.py \
  --baseline-run /path/to/base/gsm8k/run_0 \
  --sircl-run /path/to/sircl/gsm8k/run_0 \
  --output-dir /data/yhao/baseline/CODI/plots/results/sircl_boundary_gsm8k
"""

