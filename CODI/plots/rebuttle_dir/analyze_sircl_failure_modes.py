    ax.set_facecolor("#FFFFFF")
    x = np.arange(len(labels))
    bars = ax.bar(
        x,
        values,
        color=[COLOR_LIST[i % len(COLOR_LIST)] for i in range(len(labels))],
        edgecolor=BAR_EDGE_COLOR,
        linewidth=1.2,
        width=0.62,
    )

    for bar in bars:
        height = bar.get_height()
        ax.annotate(
            f"{height:.2f}",
            xy=(bar.get_x() + bar.get_width() / 2, height),
            xytext=(0, 4),
            textcoords="offset points",
            ha="center",
            va="bottom",
            fontsize=10,
        )

    ax.set_xticks(x)
    ax.set_xticklabels(labels, rotation=12, ha="right", fontsize=10)
    ax.set_ylabel("Mean pairwise latent distance", fontsize=12, fontweight="bold")
    ax.set_title("Baseline Token Diversity Across Key Groups", fontsize=13, fontweight="bold")
    ax.yaxis.grid(True, linestyle="--", alpha=GRID_ALPHA)
    ax.set_axisbelow(True)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    plt.tight_layout()
    plt.savefig(output_path, dpi=220, bbox_inches="tight", facecolor="#FFFFFF")
