@dataclass
class RunBundle:
    label: str
    run_dir: Path
    predictions: List[Any]
    ground_truth: List[Any]
    correct_mask: np.ndarray
    latents: np.ndarray
    raw_outputs: Optional[List[str]]
    metrics: Dict[str, Any]
    trajectory_stats: Dict[str, Any]
    radius_threshold: Optional[float]

    @property
    def accuracy(self) -> float:
        return float(self.correct_mask.mean()) if len(self.correct_mask) else 0.0


@dataclass
class GeometryStats:
    radii: np.ndarray
    sample_metrics: Dict[str, np.ndarray]


