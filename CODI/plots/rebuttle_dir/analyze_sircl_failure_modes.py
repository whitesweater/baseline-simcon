def build_summary_payload(
    baseline: RunBundle,
    sircl: RunBundle,
    bucket_rows: Sequence[Mapping[str, Any]],
    transition_rows: Sequence[Mapping[str, Any]],
    confidence_rows: Optional[Sequence[Mapping[str, Any]]],
    group_summary_rows: Sequence[Mapping[str, Any]],
) -> Dict[str, Any]:
    return {
        "baseline": {
            "label": baseline.label,
            "run_dir": str(baseline.run_dir),
            "accuracy": baseline.accuracy,
            "num_samples": len(baseline.predictions),
            "radius_threshold": baseline.radius_threshold,
        },
        "sircl": {
            "label": sircl.label,
            "run_dir": str(sircl.run_dir),
            "accuracy": sircl.accuracy,
            "num_samples": len(sircl.predictions),
            "radius_threshold": sircl.radius_threshold,
        },
        "absolute_gain": sircl.accuracy - baseline.accuracy,
        "relative_gain_pct": ((sircl.accuracy - baseline.accuracy) / baseline.accuracy * 100.0)
        if baseline.accuracy > EPS
        else None,
        "gain_by_baseline_bucket": list(bucket_rows),
        "transition_summary": list(transition_rows),
        "confidence_summary": list(confidence_rows) if confidence_rows is not None else None,
        "geometry_group_summary": list(group_summary_rows),
    }


def build_markdown_summary(
    summary: Mapping[str, Any],
    bucket_rows: Sequence[Mapping[str, Any]],
    transition_rows: Sequence[Mapping[str, Any]],
    group_summary_rows: Sequence[Mapping[str, Any]],
) -> str:
    baseline = summary["baseline"]
    sircl = summary["sircl"]

    base_wrong_row = row_lookup(bucket_rows, bucket="baseline_wrong")
    base_correct_row = row_lookup(bucket_rows, bucket="baseline_correct")
    wrong_base_geom = row_lookup(group_summary_rows, group="baseline_wrong", source="baseline")
    correct_base_geom = row_lookup(group_summary_rows, group="baseline_correct", source="baseline")
    recovered_base_geom = row_lookup(group_summary_rows, group="recovered", source="baseline")
    stable_wrong_base_geom = row_lookup(group_summary_rows, group="stable_wrong", source="baseline")

    lines = [
        "# SIRCL Boundary Analysis",
        "",
        "## Accuracy",
        "",
        f"- Baseline `{baseline['label']}`: {baseline['accuracy'] * 100:.2f}% ({baseline['num_samples']} samples)",
        f"- +SIRCL `{sircl['label']}`: {sircl['accuracy'] * 100:.2f}% ({sircl['num_samples']} samples)",
        f"- Absolute gain: {summary['absolute_gain'] * 100:+.2f}%",
    ]

    if summary["relative_gain_pct"] is not None:
        lines.append(f"- Relative gain: {summary['relative_gain_pct']:+.2f}%")

    lines.extend(
        [
            "",
            "## Gain By Baseline Correctness",
            "",
            "| Bucket | Count | Baseline Acc | +SIRCL Acc | Delta |",
            "| --- | ---: | ---: | ---: | ---: |",
        ]
    )
    for row in bucket_rows:
        lines.append(
            f"| {row['label']} | {row['count']} | {row['baseline_accuracy'] * 100:.2f}% | "
            f"{row['sircl_accuracy'] * 100:.2f}% | {row['absolute_gain'] * 100:+.2f}% |"
        )

    lines.extend(
        [
            "",
            "## Transition Counts",
            "",
            "| Transition | Count | Share |",
            "| --- | ---: | ---: |",
        ]
    )
    for row in transition_rows:
        lines.append(f"| {row['label']} | {row['count']} | {row['share'] * 100:.2f}% |")

    lines.extend(["", "## Geometry Highlights (Baseline Trajectories)", ""])

    if base_wrong_row and base_correct_row:
        lines.append(
            f"- Conditioned on baseline correctness, +SIRCL changes accuracy by "
            f"{base_wrong_row['absolute_gain'] * 100:+.2f}% on baseline-wrong samples and "
            f"{base_correct_row['absolute_gain'] * 100:+.2f}% on baseline-correct samples."
        )
    if wrong_base_geom and correct_base_geom:
        lines.append(
            f"- Baseline-wrong trajectories have radius_mean {wrong_base_geom['radius_mean_mean']:.3f} "
            f"vs {correct_base_geom['radius_mean_mean']:.3f} for baseline-correct ones."
        )
        lines.append(
            f"- Baseline-wrong trajectories have token diversity {wrong_base_geom['pairwise_diversity_mean_mean']:.3f} "
            f"vs {correct_base_geom['pairwise_diversity_mean_mean']:.3f} for baseline-correct ones."
        )
    if recovered_base_geom and stable_wrong_base_geom:
        lines.append(
            f"- Among baseline-wrong samples, recovered cases show radius_mean {recovered_base_geom['radius_mean_mean']:.3f} "
            f"vs {stable_wrong_base_geom['radius_mean_mean']:.3f} for still-wrong cases."
        )
        lines.append(
            f"- Among baseline-wrong samples, recovered cases show token diversity "
            f"{recovered_base_geom['pairwise_diversity_mean_mean']:.3f} vs "
            f"{stable_wrong_base_geom['pairwise_diversity_mean_mean']:.3f} for still-wrong cases."
        )

    return "\n".join(lines) + "\n"


def main() -> None:
    args = parse_args()

    baseline = load_run_bundle(args.baseline_run, args.baseline_label)
    sircl = load_run_bundle(args.sircl_run, args.sircl_label)
    validate_pair(baseline, sircl)

    auto_output_name = (
        f"sircl_boundary_{safe_name(baseline.label)}_vs_{safe_name(sircl.label)}"
    )
    output_dir = (
        Path(args.output_dir).expanduser().resolve()
        if args.output_dir
        else (SCRIPT_DIR / "results" / auto_output_name).resolve()
    )
    output_dir.mkdir(parents=True, exist_ok=True)

    baseline_geom = compute_geometry_stats(baseline.latents, baseline.radius_threshold)
    sircl_geom = compute_geometry_stats(sircl.latents, sircl.radius_threshold)

    group_masks = build_group_masks(baseline.correct_mask, sircl.correct_mask)
    rng = np.random.default_rng(args.seed)
    group_indices = build_group_indices(group_masks, args.max_samples_per_group, rng)

    baseline_confidences = None
    confidence_rows = None
    if args.baseline_confidence_file:
        baseline_confidences = load_confidence_scores(
            args.baseline_confidence_file,
            expected_length=len(baseline.predictions),
        )
        bins = parse_confidence_bins(args.confidence_bins)
        confidence_rows = summarize_confidence_buckets(
            baseline_confidences,
            bins,
            baseline.correct_mask,
            sircl.correct_mask,
        )

    bucket_rows = summarize_accuracy_by_baseline_bucket(baseline.correct_mask, sircl.correct_mask)
    transition_rows = summarize_transitions(group_masks, total_samples=len(baseline.predictions))
    group_summary_rows = summarize_geometry_groups(group_masks, group_indices, baseline_geom, sircl_geom)
    radius_profile_rows = summarize_radius_profiles(group_indices, baseline_geom, sircl_geom)
    sample_level_rows = build_sample_level_rows(
        baseline,
        sircl,
        baseline_geom,
        sircl_geom,
        group_masks,
        baseline_confidences,
    )
    failure_example_rows = build_failure_examples(
        baseline,
        sircl,
        baseline_geom,
        sircl_geom,
        group_masks,
        max_examples_per_transition=args.max_examples_per_transition,
    )

    write_csv(output_dir / "sample_level.csv", sample_level_rows)
    write_csv(output_dir / "gain_by_baseline_bucket.csv", bucket_rows)
    write_csv(output_dir / "transition_summary.csv", transition_rows)
    write_csv(output_dir / "geometry_group_summary.csv", group_summary_rows)
    write_csv(output_dir / "radius_profiles.csv", radius_profile_rows)
    write_csv(output_dir / "failure_examples.csv", failure_example_rows)
    if confidence_rows is not None:
        write_csv(output_dir / "gain_by_confidence_bucket.csv", confidence_rows)

    plot_accuracy_gain(
        bucket_rows,
        baseline_label=baseline.label,
        sircl_label=sircl.label,
        output_path=output_dir / "accuracy_gain_by_baseline_bucket.png",
    )
    plot_radius_profiles_for_groups(
        group_names=["baseline_correct", "baseline_wrong"],
        group_indices=group_indices,
        radii=baseline_geom.radii,
        title="Baseline $r_t$ Profile: Correct vs Wrong",
        output_path=output_dir / "baseline_rt_by_correctness.png",
    )
    plot_radius_profiles_for_groups(
        group_names=["recovered", "stable_wrong"],
        group_indices=group_indices,
        radii=baseline_geom.radii,
        title="Baseline-Wrong Samples: Recovered vs Still Wrong",
        output_path=output_dir / "baseline_wrong_rt_split.png",
    )
    plot_diversity_bars(
        group_names=["baseline_correct", "baseline_wrong", "recovered", "stable_wrong"],
        group_indices=group_indices,
        baseline_geom=baseline_geom,
        output_path=output_dir / "baseline_group_diversity.png",
    )

    summary_payload = build_summary_payload(
        baseline=baseline,
        sircl=sircl,
        bucket_rows=bucket_rows,
        transition_rows=transition_rows,
        confidence_rows=confidence_rows,
        group_summary_rows=group_summary_rows,
    )
    with (output_dir / "summary.json").open("w", encoding="utf-8") as f:
        json.dump(summary_payload, f, ensure_ascii=False, indent=2)

    summary_md = build_markdown_summary(
        summary_payload,
        bucket_rows=bucket_rows,
        transition_rows=transition_rows,
        group_summary_rows=group_summary_rows,
    )
    (output_dir / "summary.md").write_text(summary_md, encoding="utf-8")

    print("=" * 80)
    print("SIRCL boundary analysis complete")
    print("=" * 80)
    print(f"Baseline: {baseline.label}")
    print(f"  Accuracy: {baseline.accuracy * 100:.2f}%")
    print(f"  Run dir : {baseline.run_dir}")
    print(f"+SIRCL  : {sircl.label}")
    print(f"  Accuracy: {sircl.accuracy * 100:.2f}%")
    print(f"  Run dir : {sircl.run_dir}")
    print(f"Absolute gain: {(sircl.accuracy - baseline.accuracy) * 100:+.2f}%")
    print(f"Output dir: {output_dir}")


if __name__ == "__main__":
    main()
